create table public.role_skill_requirements (
  role_slug text not null references public.roles(slug) on delete cascade,
  skill_id uuid not null references public.skills(id) on delete cascade,
  importance smallint not null default 1 check (importance between 1 and 5),
  primary key (role_slug, skill_id)
);
alter table public.role_skill_requirements enable row level security;
create policy "authenticated read role skill requirements"
  on public.role_skill_requirements for select to authenticated using (true);
revoke all on public.role_skill_requirements from anon, authenticated;
grant select on public.role_skill_requirements to authenticated;

